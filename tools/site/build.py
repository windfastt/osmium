#!/usr/bin/env python3
"""Build the product page docs/index.html from tools/site/template.html and the repository's own data.

Inputs (all in this repository):
  Directory.Build.props                 version
  docs/benchmarks-*.json                benchmark results written by tools/crosscheck.py (newest file wins)
  tools/site/data/benchmark-conditions.json   machine, date and tool versions of that benchmark run
  tools/site/data/ultra-mixed.*.txt     `osmium info` / `osmium explain` of the Ultra archive of the mixed folder
  docs/SETTINGS.md                      settings count (generated by tools/settingsdoc)
  docs/img/manifest.json                real screenshots rendered by the app's self-test on Windows CI
                                        (fetched with tools/site/fetch_screenshots.py); optional

Usage:
  python3 tools/site/build.py           write docs/index.html
  python3 tools/site/build.py --check   exit 1 if docs/index.html is not up to date (CI)
"""
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "tools" / "site"
DOCS = ROOT / "docs"

SHORT = {
    "zip": ("zip -9", "zip -r -9"),
    "bzip2": ("bzip2 -9", "tar | bzip2 -9"),
    "brotli": ("Brotli 11", "tar | brotli -q 11 -w 24"),
    "zstd": ("Zstandard 22", "tar | zstd --ultra -22 --long=31 -T1"),
    "xz": ("xz -9e", "tar | xz -9e -T1"),
    "7z": ("7-Zip LZMA2", "7z a -mx=9 -m0=lzma2 -mfb=273 -md=256m -ms=on"),
    "7z-ppmd": ("7-Zip PPMd", "7z a -m0=PPMd:mem=1024m:o=32 -ms=on"),
    "lrzip": ("lrzip -z", "tar | lrzip -z -L 9 (ZPAQ back end)"),
    "zpaq": ("ZPAQ -m5", "zpaq a -m5"),
}
DATASETS = {
    "mixed-folder": ("Mixed folder", "{mib} MiB, {files} files: license texts, ELF and .NET binaries, PNG and gzip files and "
                     "duplicates, plus four files generated for the test: a CSV, 12-byte telemetry records, a WAV and a BMP."),
    "windows-app": ("Folder of program files", "{mib} MiB, {files} files: Osmium's own self-contained Windows build, mostly .NET "
                    "runtime DLLs (ReadyToRun) and native x64 DLLs and EXEs, the kind of payload an installer ships."),
}
# Gallery order and tab labels for screenshot ids (file name without extension and without "-dark").
GALLERY = [
    ("page-compress-filled", "Compress"), ("page-compress", "Compress"), ("page-jobs", "Jobs"), ("page-archives", "Archives"),
    ("page-lab", "Lab"), ("page-rules", "Rules"), ("page-cluster", "Cluster"), ("settings-experimental", "Settings"),
    ("settings-general", "Settings"), ("dialog-tune", "Tune dialog"), ("tray-menu", "Tray menu"), ("dialog-about", "About"),
]
FAVICON = ("data:image/svg+xml," + (
    "<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'><defs><linearGradient id='g' x1='0' y1='0' x2='1' y2='1'>"
    "<stop offset='0' stop-color='%233a2a96'/><stop offset='1' stop-color='%2314a0d2'/></linearGradient></defs>"
    "<rect x='1.3' y='1.3' width='29.4' height='29.4' rx='7' fill='url(%23g)'/>"
    "<polygon points='16,5.8 25.1,11 16,16.3 6.9,11' fill='%23f0f4ff'/><polygon points='25.1,11 25.1,21.6 16,26.9 16,16.3' fill='%23aab6d7'/>"
    "<polygon points='6.9,11 16,16.3 16,26.9 6.9,21.6' fill='%237884af'/></svg>"))


def pct(x):
    return f"{x * 100:.1f} %"


def signed(x):
    return ("−" if x < 0 else "+") + f"{abs(x) * 100:.1f} %"


def secs(s):
    # the same format as the page's charts and tables (secs() in the template's script)
    return (f"{s:.1f} s" if s < 10 else f"{round(s)} s" if s < 90
            else f"{int(s // 60)} min {round(s % 60):02d} s" if s < 5400 else f"{s / 3600:.1f} h")


def keep(text):
    """No line break between a number and its unit, or between a tool and its switch, in the narrow result tiles."""
    text = re.sub(r"(\d) (%|s\b|min\b|bytes\b)", "\\1\u00a0\\2", text)
    text = re.sub(r"\bmin (\d)", "min\u00a0\\1", text)
    text = re.sub(r"\b(7-Zip|ZPAQ|lrzip|xz) -", "\\1\u00a0-\u2060", text)   # U+2060 (word joiner): no break after a hyphen
    return text.replace("7-Zip", "7-\u2060Zip")


def version():
    m = re.search(r"<Version>([^<]+)</Version>", (ROOT / "Directory.Build.props").read_text())
    return m.group(1)


def bench_file():
    files = sorted(DOCS.glob("benchmarks-*.json"), key=lambda p: [int(x) for x in re.findall(r"\d+", p.stem)])
    return files[-1]


def bench_data(raw):
    order = [d for d in DATASETS if any(r["dataset"] == d for r in raw)]
    datasets, rows = [], []
    for d in order:
        first = next(r for r in raw if r["dataset"] == d)
        title, desc = DATASETS[d]
        datasets.append({"id": d, "title": title, "bytes": first["dataset_bytes"], "files": first["files"],
                         "desc": desc.format(mib=f"{first['dataset_bytes'] / 2**20:.1f}", files=first["files"])})
    for r in raw:
        if r["dataset"] not in DATASETS or not r.get("ok"):
            continue
        fam = r["family"]
        if fam.startswith("osmium-"):
            prof = fam[7:]
            tool, setting = "Osmium " + prof.capitalize(), f"osmium a --profile {prof}"
        else:
            tool, setting = SHORT[fam]
        rows.append({"ds": r["dataset"], "tool": tool, "setting": setting, "fam": fam, "bytes": r["bytes"],
                     "c": r["compress_s"], "d": r["decompress_s"], "ok": True})

    def get(ds, fam):
        return next((r for r in rows if r["ds"] == ds and r["fam"] == fam), None)

    def best(ds, osm):
        c = [r for r in rows if r["ds"] == ds and r["fam"].startswith("osmium") == osm]
        return min(c, key=lambda r: r["bytes"]) if c else None

    # Every size tile names the profile, the baseline (7-Zip -mx9), the folder, and both times next to the percentage.
    tiles = []
    for ds in datasets:
        sz, bo, bt = get(ds["id"], "7z"), best(ds["id"], True), best(ds["id"], False)
        if not (sz and bo):
            continue
        mixed = ds["id"] == "mixed-folder"
        cap = (f"{bo['tool']}: {pct(bo['bytes'] / ds['bytes'])} of the original, against {pct(sz['bytes'] / ds['bytes'])}. "
               f"Compress {secs(bo['c'])} against {secs(sz['c'])}, extract {secs(bo['d'])} against {secs(sz['d'])}, "
               f"with Osmium on 4 cores and 7-Zip at its default threading")
        if bt and bt["bytes"] < bo["bytes"]:
            cap += f". {bt['tool']} is smaller still: {pct(bt['bytes'] / ds['bytes'])}"
        tiles.append({"v": signed(bo["bytes"] / sz["bytes"] - 1),
                      "l": f"vs 7-Zip -mx9 on the {ds['title'].lower()} in our test" + (", which includes generated files" if mixed else ""),
                      "c": cap})
        if mixed and bt and bo["bytes"] < bt["bytes"]:
            tiles.append({"v": signed(bo["bytes"] / bt["bytes"] - 1),
                          "l": f"vs {bt['tool']}, the smallest other result on the same mixed folder",
                          "c": f"{bo['tool']} {bo['bytes']:,} bytes, {bt['tool']} {bt['bytes']:,} bytes. Compress {secs(bo['c'])} "
                               f"against {secs(bt['c'])}, extract {secs(bo['d'])} against {secs(bt['d'])}, with Osmium on 4 cores "
                               f"and {bt['tool'].split()[0]} at its default threading"})
    n_ok = sum(1 for r in raw if r.get("ok"))
    n_run = sum(1 for r in raw if "bytes" in r)
    tiles.append({"v": f"{n_ok} of {n_run}", "l": "benchmark archives unpacked byte-identical",
                  "c": "every run in the table below, checked file by file"})
    tiles = [{k: keep(v) for k, v in t.items()} for t in tiles]
    return {"datasets": datasets, "rows": rows, "tiles": tiles[:4]}


def planner_rows():
    info = (SITE / "data" / "ultra-mixed.info.txt").read_text()
    explain = (SITE / "data" / "ultra-mixed.explain.txt").read_text().splitlines()
    blocks = re.findall(r"#\d+\s+([\d.]+ [KMG]?i?B) →\s+([\d.]+ [KMG]?i?B)\s+(.+)", info)
    groups, cur = [], None
    for line in explain:
        m = re.match(r"group (\d+): (\w+), (\d+) unit\(s\), ([\d,]+) bytes(?:, e\.g\. (.+))?", line)
        if m:
            cur = {"cls": m[2], "units": int(m[3]), "fmt": m[5] or "", "rungs": [], "search": [], "chose": None, "forced": None}
            groups.append(cur)
            continue
        line = line.strip()
        if line.startswith("rung "):
            cur["rungs"].append(line.count(" = "))
        elif line.startswith("search: "):
            m2 = re.search(r"improves ([\d,]+) → ([\d,]+)", line)
            cur["search"].append((int(m2[1].replace(",", "")), int(m2[2].replace(",", ""))))
        elif line.startswith("chose "):
            cur["chose"] = line[6:].split(" (race")[0]
        elif line.startswith("forced pipeline: "):
            cur["forced"] = line[len("forced pipeline: "):]
    seen = {
        "Text": "{u} files: license texts, a generated CSV and a short UTF-8 file",
        "CodeX86": "libcrypto.so.3 and xz: x64 machine code (ELF)",
        "Binary": "Microsoft.Build.dll: .NET IL, no native code",
        "Structured": "telemetry.dat: 12-byte records, generated",
        "Audio": "tone.wav: 16-bit stereo PCM, generated",
        "Image": "gradient.bmp: 400×300, 24-bit, generated",
        "Incompressible": "3 PNG and 3 gzip files",
    }
    out = []
    for g, (raw, packed, pipe) in zip(groups, blocks):
        spec = g["chose"] or g["forced"]
        assert spec == pipe.strip(), (spec, pipe)
        if g["forced"]:
            note = "stored as-is by the built-in rule for compressed formats"
        else:
            cands = g["rungs"][0] if g["rungs"] else 1
            if g["search"]:
                start, end = g["search"][0][0], g["search"][-1][1]
                note = f"best of {cands} candidates, then parameter search: {signed(end / start - 1)} on the sample"
            else:
                note = f"best of {cands} candidates; parameter search found nothing better"
        out.append("<tr><td>{cls}</td><td>{seen}</td><td class=\"n\">{raw}</td><td class=\"n\">{packed}</td>"
                   "<td><code>{pipe}</code><span class=\"k\">{note}</span></td></tr>".format(
                       cls=html.escape(g["cls"]), seen=html.escape(seen.get(g["cls"], g["fmt"]).format(u=g["units"])),
                       raw=raw, packed=packed, pipe=html.escape(spec), note=html.escape(note)))
    return "\n".join(out)


def settings_count():
    m = re.search(r"\*\*(\d+) settings in (\d+) categories\*\*", (DOCS / "SETTINGS.md").read_text())
    return f"{m.group(1)} settings in {m.group(2)} categories"


def conditions():
    c = json.loads((SITE / "data" / "benchmark-conditions.json").read_text())
    tools = ", ".join(f"{k} {v}" for k, v in c["versions"].items())
    corpus = DOCS / f"{bench_file().stem}-corpus.sha256"   # the SHA-256 of every file the benchmark measured
    if not corpus.exists():
        raise SystemExit(f"missing {corpus.relative_to(ROOT)}: every published result needs its corpus hash list")
    cond = (f"Measured on {c['date']} on one machine ({c['machine']}) with {tools}. Times are wall-clock seconds on that "
            f"machine. Full tables and commands: <a href=\"https://github.com/windfastt/osmium/blob/main/docs/BENCHMARKS.md\">BENCHMARKS.md</a>; "
            f"the SHA-256 of every file measured: <a href=\"https://github.com/windfastt/osmium/blob/main/docs/{corpus.name}\">{corpus.name}</a>.")
    disclaimer = (f"The results come from two test folders, one of which includes files generated for the test, measured once on "
                  f"one machine ({c['machine']}, {c['date']}) "
                  f"with the tool versions and settings listed in "
                  f"<a href=\"https://github.com/windfastt/osmium/blob/main/docs/BENCHMARKS.md\">BENCHMARKS.md</a>. "
                  f"Other data, versions and hardware will give different results; rerun them with "
                  f"<code>tools/crosscheck.py</code>.")
    return cond, disclaimer


def picture(shots, sid, alt, cls=""):
    light = shots.get(sid)
    dark = shots.get(sid + "-dark")
    if not light:
        return ""
    src = html.escape(light["file"])
    dark_src = f'<source srcset="img/{html.escape(dark["file"])}" media="(prefers-color-scheme: dark)">' if dark else ""
    return (f'<picture{(" class=" + chr(34) + cls + chr(34)) if cls else ""}>{dark_src}<img src="img/{src}" width="{light["width"]}" '
            f'height="{light["height"]}" alt="{html.escape(alt)}" loading="lazy" decoding="async"></picture>')


def screenshots():
    path = DOCS / "img" / "manifest.json"
    if not path.exists():
        return None
    shots = {}
    for e in json.loads(path.read_text()):
        sid = re.sub(r"\.(png|webp)$", "", e["file"])
        shots[sid] = e
    return shots


def hero_and_gallery():
    shots = screenshots()
    if not shots:
        hero = """      <figure class="shot hero-shot">
        <div class="card" style="display:grid;gap:10px">
          <h3>What it does</h3>
          <p class="body">Seven profiles from Store to Exhaustive · per-kind pipelines with x86/x64, ARM64, delta, record,
            audio, image and text filters · LZMA, PPMd, Zstandard, Brotli, BZip2, Deflate and Osmium's own context-mixing
            codec · whole-file and chunk deduplication · AES-256-GCM encryption · optional help from other PCs.</p>
        </div>
      </figure>"""
        gallery = """    <p class="body">The app has eight pages — Compress, Jobs, Archives, Lab, Rules, Cluster, Settings and Log — and a tray
      menu with the default profile, recent jobs, pause, watch folders and lending this PC to a cluster.</p>"""
        return hero, gallery
    compress = next((sid for sid in ("page-compress-filled", "page-compress") if sid in shots), None)
    hero_img = picture(shots, compress, shots[compress]["caption"]) if compress else ""
    inset = picture(shots, "tray-menu", shots["tray-menu"]["caption"]) if "tray-menu" in shots else ""
    hero = f"""      <figure class="shot hero-shot">
        {hero_img}
        {('<div class="inset">' + inset + '</div>') if inset else ''}
        <figcaption>The real app: {html.escape(shots[compress]['caption'][0].lower() + shots[compress]['caption'][1:]) if compress else ''}. Rendered by the app itself on a Windows test machine.</figcaption>
      </figure>"""
    tabs, panels, used = [], [], set()
    for sid, label in GALLERY:
        if sid not in shots or label in used:
            continue
        used.add(label)
        i = len(tabs)
        tabs.append(f'<button type="button" role="tab" id="tab-{i}" aria-controls="panel-{i}" aria-selected="{"true" if i == 0 else "false"}">{html.escape(label)}</button>')
        panels.append(f'<div class="panel" role="tabpanel" id="panel-{i}" aria-labelledby="tab-{i}"><figure class="shot">{picture(shots, sid, shots[sid]["caption"])}'
                      f'<figcaption>{html.escape(shots[sid]["caption"])}</figcaption></figure></div>')
    gallery = f"""    <div class="gallery">
      <div class="tabs" role="tablist" aria-label="Screenshots">{''.join(tabs)}</div>
      {''.join(panels)}
      <p class="shot-note">Every screenshot is rendered by the app itself during CI, on a Windows test machine, from a sample
        folder it creates (text, CSV, BMP, WAV, a DLL and a PNG). Nothing in them is mocked up.</p>
    </div>"""
    return hero, gallery


def build():
    raw = json.loads(bench_file().read_text())
    data = json.dumps(bench_data(raw), ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    cond, disclaimer = conditions()
    hero, gallery = hero_and_gallery()
    page = (SITE / "template.html").read_text()
    repl = {
        "{{FAVICON}}": FAVICON, "{{VERSION}}": version(), "{{SETTINGS_COUNT}}": settings_count(),
        "{{CONDITIONS}}": cond, "{{BENCH_DISCLAIMER}}": disclaimer, "{{HERO}}": hero, "{{GALLERY}}": gallery,
        "/*BENCH*/": data,
        '<tbody id="plan-rows" data-fill="planner"></tbody>': f'<tbody id="plan-rows">\n{planner_rows()}\n</tbody>',
    }
    for k, v in repl.items():
        if k not in page:
            raise SystemExit(f"template is missing {k}")
        page = page.replace(k, v)
    left = re.findall(r"\{\{[A-Z_]+\}\}|data-fill=", page)
    if left:
        raise SystemExit(f"unfilled placeholders: {left}")
    return page


def main():
    page = build()
    out = DOCS / "index.html"
    if "--check" in sys.argv:
        if not out.exists() or out.read_text() != page:
            print("docs/index.html is out of date: run python3 tools/site/build.py", file=sys.stderr)
            return 1
        print("docs/index.html is up to date")
        return 0
    out.write_text(page)
    print(f"wrote {out.relative_to(ROOT)} ({len(page):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
